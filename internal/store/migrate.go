package store

import (
	"database/sql"
	"embed"
	"fmt"

	_ "github.com/jackc/pgx/v5/stdlib" // registers the "pgx" database/sql driver
	"github.com/pressly/goose/v3"
)

//go:embed migrations/*.sql
var migrationsFS embed.FS

// Migrate applies all pending migrations against dsn. It is run as an
// explicit step (the `cinc-collector migrate` subcommand), not
// automatically on every server boot: with N Cinc Collector replicas
// starting concurrently against shared SereneDB, auto-migrating on boot
// would race. goose needs a database/sql connection, so this opens one via
// pgx's stdlib driver independently of the pgxpool used elsewhere.
func Migrate(dsn string) error {
	db, err := sql.Open("pgx", dsn)
	if err != nil {
		return fmt.Errorf("store: open migration connection: %w", err)
	}
	defer func() { _ = db.Close() }()

	if err := ensureGooseVersionTable(db); err != nil {
		return fmt.Errorf("store: bootstrap migration tracking table: %w", err)
	}

	goose.SetBaseFS(migrationsFS)
	if err := goose.SetDialect("postgres"); err != nil {
		return err
	}
	return goose.Up(db, "migrations")
}

// ensureGooseVersionTable pre-creates goose's own bookkeeping table using
// SereneDB-compatible DDL. goose's built-in bootstrap (triggered only if a
// SELECT against this table fails, so pre-creating it short-circuits that
// path entirely) uses "id integer PRIMARY KEY GENERATED BY DEFAULT AS
// IDENTITY", which SereneDB rejects; SERIAL is the compatible equivalent.
// Column names/types and the seed row otherwise match goose's own
// bootstrap exactly, so goose's normal version-tracking queries work
// unmodified against it.
func ensureGooseVersionTable(db *sql.DB) error {
	var discard int
	err := db.QueryRow(`SELECT 1 FROM goose_db_version LIMIT 1`).Scan(&discard)
	if err == nil || err == sql.ErrNoRows {
		return nil // table already exists
	}

	_, err = db.Exec(`
		CREATE TABLE goose_db_version (
			id         SERIAL PRIMARY KEY,
			version_id BIGINT NOT NULL,
			is_applied BOOLEAN NOT NULL,
			tstamp     TIMESTAMP NOT NULL DEFAULT now()
		)
	`)
	if err != nil {
		return err
	}
	_, err = db.Exec(`INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true)`)
	return err
}
